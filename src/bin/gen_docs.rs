use std::{fs::File, io::Write};

use chrono::Local;
use clap::CommandFactory;
use zellij_mcp_server::{interactive::ReplCommand, mcp::tools};

fn render_subcmd_docs(doc: &mut String, cmd: &mut clap::Command, prefix: &str, depth: usize) {
    let name = cmd.get_name().to_string();
    if name == "help" {
        return;
    }

    let full_path = if prefix.is_empty() {
        name.clone()
    } else {
        format!("{} {}", prefix, name)
    };

    let heading = "#".repeat(depth);
    doc.push_str(&format!("{} {}\n\n", heading, full_path));
    doc.push_str(&format!("```text\n>>> {} --help\n", full_path));
    doc.push_str(&cmd.render_long_help().to_string()); // &mut 借用结束
    doc.push_str("```\n\n");

    // 递归处理子命令，depth+1 加深标题层级
    for subcmd in cmd.get_subcommands_mut() {
        render_subcmd_docs(doc, subcmd, &full_path, depth + 1);
    }
}

fn gen_cli_docs() -> std::io::Result<()> {
    let mut repl_cmd = ReplCommand::command().override_usage("<COMMAND>");

    let mut doc = String::new();

    let current_date = Local::now().format("%Y-%m-%d").to_string();
    doc.push_str(" - Generated by [gen_docs.rs](../src/bin/gen_docs.rs), do not edit!\n");
    doc.push_str(&format!(" - Generate date: {}\n\n", current_date));

    doc.push_str("# Zellij MCP Server CLI Commands\n\n");

    doc.push_str("```text\n>>> help\n");
    doc.push_str(&repl_cmd.render_help().to_string());
    doc.push_str("```\n\n");

    for subcmd in repl_cmd.get_subcommands_mut() {
        render_subcmd_docs(&mut doc, subcmd, "", 2);
    }

    let mut file = File::create("docs/cli-command.md")?;
    file.write_all(doc.as_bytes())?;
    Ok(())
}

fn extract_type(schema: &serde_json::Value) -> String {
    // schemars 1.x 用 anyOf 表示 Option<T>: [{type: T}, {type: null}]
    if let Some(any_of) = schema.get("anyOf").and_then(|v| v.as_array()) {
        let non_null: Vec<String> = any_of
            .iter()
            .filter(|s| s.get("type").and_then(|t| t.as_str()) != Some("null"))
            .map(|s| extract_type(s))
            .collect();
        return if non_null.len() == 1 {
            format!("{}?", non_null[0])
        } else {
            non_null.join(" | ")
        };
    }
    // Vec<T> → array
    if schema.get("type").and_then(|t| t.as_str()) == Some("array") {
        let item_ty = schema
            .get("items")
            .map(|items| extract_type(items))
            .unwrap_or_else(|| "any".to_string());
        return format!("{}[]", item_ty);
    }
    // ["string", "null"] 形式的 nullable type
    if let Some(type_arr) = schema.get("type").and_then(|t| t.as_array()) {
        let non_null: Vec<&str> = type_arr
            .iter()
            .filter_map(|v| v.as_str())
            .filter(|s| *s != "null")
            .collect();
        return if non_null.len() == 1 {
            format!("{}?", non_null[0])
        } else {
            non_null.join(" | ")
        };
    }
    // 普通类型
    schema
        .get("type")
        .and_then(|t| t.as_str())
        .unwrap_or("any")
        .to_string()
}

fn gen_mcp_docs() -> std::io::Result<()> {
    let mut doc = String::new();
    let tool_router =
        tools::session::tool_router() + tools::tab::tool_router() + tools::readwrite::tool_router();
    let mut mcp_tools = tool_router.list_all();
    mcp_tools.sort_by(|a, b| a.name.cmp(&b.name));

    let current_date = Local::now().format("%Y-%m-%d").to_string();
    doc.push_str(" - Generated by [gen_docs.rs](../src/bin/gen_docs.rs), do not edit!\n");
    doc.push_str(&format!(" - Generate date: {}\n\n", current_date));

    doc.push_str("# MCP Tools\n\n");

    for tool in mcp_tools {
        doc.push_str(&format!("## {}\n\n", tool.name));
        if let Some(desc) = &tool.description {
            doc.push_str(&format!("{}\n\n", desc));
        }
        // 从 JSON Schema 中提取参数信息
        if let Some(props) = tool
            .input_schema
            .get("properties")
            .and_then(|p| p.as_object())
        {
            let required: Vec<&str> = tool
                .input_schema
                .get("required")
                .and_then(|r| r.as_array())
                .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
                .unwrap_or_default();

            doc.push_str("**Parameters:**\n\n");
            for (param, schema) in props {
                let ty = extract_type(schema);
                let desc = schema
                    .get("description")
                    .and_then(|d| d.as_str())
                    .unwrap_or("");
                let req_label = if required.contains(&param.as_str()) {
                    "*(required)*"
                } else {
                    "*(optional)*"
                };
                doc.push_str(&format!("- **`{}`** `{}` {}\n\n", param, ty, req_label));
                for line in desc.lines() {
                    if line.trim().is_empty() {
                        doc.push('\n');
                    } else {
                        doc.push_str(&format!("  {}\n", line));
                    }
                }
                doc.push('\n');
            }
            doc.push('\n');
        }
    }

    let mut file = File::create("docs/mcp-command.md")?;
    file.write_all(doc.as_bytes())?;
    Ok(())
}

fn main() -> std::io::Result<()> {
    gen_cli_docs()?;
    gen_mcp_docs()
}
